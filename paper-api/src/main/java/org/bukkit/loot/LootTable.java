package org.bukkit.loot;

import io.papermc.paper.loot.LootContextKey;
import java.util.Collection;
import java.util.Random;
import java.util.Set;
import org.bukkit.Keyed;
import org.bukkit.inventory.Inventory;
import org.bukkit.inventory.ItemStack;
import org.jetbrains.annotations.Unmodifiable;
import org.jspecify.annotations.Nullable;

/**
 * LootTables are technical files that represent what items should be in
 * naturally generated containers, what items should be dropped when killing a
 * mob, or what items can be fished.
 * <br>
 * See the <a href="https://minecraft.wiki/w/Loot_table">
 * Minecraft Wiki</a> for more information.
 */
public interface LootTable extends Keyed {

    /**
     * Returns a mutable list of loot generated by this LootTable.
     *
     * @param random the random instance to use to generate loot
     * @param context context within to populate loot
     * @return a list of ItemStacks
     * @deprecated the random instance is provided through the loot context, use {@link #populateLoot(LootContext)}
     */
    @Deprecated(since = "26.4")
    default Collection<ItemStack> populateLoot(final @Nullable Random random, final LootContext context) {
        return this.populateLoot(random == null ? context : context.toBuilder().withRandom(random).build());
    }

    /**
     * Returns a mutable list of loot generated by this LootTable.
     *
     * @param context context within to populate loot
     * @return a list of ItemStacks
     */
    Collection<ItemStack> populateLoot(LootContext context);

    /**
     * Attempt to fill an inventory with this LootTable's loot.
     *
     * @param inventory the inventory to fill
     * @param random the random instance to use to generate loot
     * @param context context within to populate loot
     * @deprecated the random instance is provided through the loot context, use {@link #fillInventory(Inventory, LootContext)}
     */
    @Deprecated(since = "26.4")
    default void fillInventory(final Inventory inventory, final @Nullable Random random, final LootContext context) {
        this.fillInventory(inventory, random == null ? context : context.toBuilder().withRandom(random).build());
    }

    /**
     * Attempt to fill an inventory with this LootTable's loot.
     *
     * @param inventory the inventory to fill
     * @param context context within to populate loot
     */
    void fillInventory(Inventory inventory, LootContext context);

    /**
     * Gets the loot context keys required to be set in {@link LootContext} for this loot table.
     *
     * @return the required keys
     */
    @Unmodifiable Set<LootContextKey> requiredContextKeys();

    /**
     * Gets the required and optional loot context keys to be set in {@link LootContext} for this loot table.
     *
     * @return the allowed keys
     */
    @Unmodifiable Set<LootContextKey> allowedContextKeys();

    /**
     * Checks if the given context passes validation for this loot table, meaning it can be used
     * to {@link #populateLoot(LootContext) populate loot} or {@link #fillInventory(Inventory, LootContext) fill an inventory}.
     * <p>
     * A context is valid if it contains all the {@link #requiredContextKeys() required keys}. Keys that
     * are not {@link #allowedContextKeys() allowed} by this loot table are ignored when generating loot,
     * so they do not make a context invalid. Some loot tables require internal keys that cannot be
     * supplied through the API, in which case no context is valid.
     *
     * @param context the context to check
     * @return {@code true} if the context passes validation
     */
    boolean isValidContext(LootContext context);

    /**
     * Checks if the context built from the given builder passes validation for this loot table.
     *
     * @param builder the builder to check
     * @return {@code true} if the built context passes validation
     * @see #isValidContext(LootContext)
     */
    default boolean isValidContext(final LootContext.Builder builder) {
        return this.isValidContext(builder.build());
    }
}
